    /**
     * Tracé de la zone A vers la zone B (clés courtes), ou null si aucun trajet connu.
     *
     * @return list<array{0: float, 1: float}>|null
     */
    public static function path(string $from, string $to): ?array
    {
        if (isset(self::LEGS["$from>$to"])) {
            return self::LEGS["$from>$to"];
        }

        return isset(self::LEGS["$to>$from"]) ? array_reverse(self::LEGS["$to>$from"]) : null;
    }

    /** Clé courte d'une zone à partir de son nom. */
    public static function keyOf(string $zoneName): ?string
    {
        return array_search($zoneName, self::ZONES, true) ?: null;
    }

    /** Destinations atteignables depuis une zone. @return list<string> */
    public static function neighbours(string $key): array
    {
        $n = [];
        foreach (array_keys(self::LEGS) as $leg) {
            [$a, $b] = explode('>', $leg);
            if ($a === $key) $n[] = $b;
            if ($b === $key) $n[] = $a;
        }

        return $n;
    }
